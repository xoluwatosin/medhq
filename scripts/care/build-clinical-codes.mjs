// Mirrors the governed clinical codes into the edge-function shared folder so
// the server can check an answer against exactly the same vocabulary the
// browser offered. Run with: bun scripts/care/build-clinical-codes.mjs
import { writeFileSync } from "node:fs";

const {
  MEDICINES, ALLERGENS, CONDITIONS,
  ALLERGY_SEVERITIES, ALLERGY_REACTIONS,
  CLINICAL_VOCABULARY, CLINICAL_VOCABULARY_VERSION,
} = await import("../../src/lib/care-clinical-lists.ts");

const active = (list) => list.filter((t) => t.active !== false).map((t) => t.code).sort();
const codes = (groups) => groups.map((g) => g.code);

const body = `// GENERATED by scripts/care/build-clinical-codes.mjs — do not edit by hand.
//
// The governed clinical codes, mirrored from src/lib/care-clinical-lists.ts so
// that server validation and browser validation accept exactly the same terms.
export const CLINICAL_VOCABULARY = ${JSON.stringify(CLINICAL_VOCABULARY)};
export const CLINICAL_VOCABULARY_VERSION = ${CLINICAL_VOCABULARY_VERSION};

export const ACTIVE_MEDICINE_CODES = new Set(${JSON.stringify(active(MEDICINES))});
export const ACTIVE_ALLERGEN_CODES = new Set(${JSON.stringify(active(ALLERGENS))});
export const ACTIVE_CONDITION_CODES = new Set(${JSON.stringify(active(CONDITIONS))});
export const ALLERGY_SEVERITY_CODES = new Set(${JSON.stringify(codes(ALLERGY_SEVERITIES))});
export const ALLERGY_REACTION_CODES = new Set(${JSON.stringify(codes(ALLERGY_REACTIONS))});
`;

writeFileSync(new URL("../../supabase/functions/_shared/care-clinical-codes.ts", import.meta.url), body);
console.log("clinical codes written");
